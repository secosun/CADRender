def generate_catalog():
    # Start with legacy colors
    colors = dict(LEGACY_COLORS)

    # Add RAL colors
    for code, name_zh, hex_val in RAL_COLORS:
        linear_rgba = hex_to_linear_rgba(hex_val)
        key = ral_key(code)
        colors[key] = {
            "label_zh": name_zh,
            "label_en": f"RAL {code}",
            "principled": {
                "base_color": linear_rgba
            }
        }

    catalog = {
        "version": 2,
        "description": "RAL K7 Classic 标准色库 + 原有喷粉色。颜色值由 RAL 官方 sRGB 转换至 Blender 线性空间。",
        "colors": colors
    }
    return catalog

